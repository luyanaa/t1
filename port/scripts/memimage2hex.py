#!/usr/bin/env python3
"""Convert mbfw_diag_memimage.c C-array memory images to a $readmemh file.

Input : port/firmware/mbfw_diag_memimage.c
        Arrays named MI_<16-hex-digit-physical-base-address>, each element a
        uint64_t stored consecutively starting at that base address.

Output: port/stim/l2_buf.mem  (sparse $readmemh image)

@addr semantics
---------------
ADDR_STEP = 8: every `@<addr>` record and the implicit +1-per-word advance is
in units of 64-bit words (i.e. addr = physical_byte_address / 8).  A Verilog
responder with `reg [63:0] mem[]` loaded by
`$readmemh("l2_buf.mem", mem)` then looks up data for physical address `pa`
with `mem[pa >> 3]` and gets the exact C-array element stored at `pa`.
8 bytes is the natural granularity because every array element is a 64-bit
word and T1 IFILL/DFILL requests are 16B/64B multiples of it.

Value format: one 16-hex-digit word per line, ULL suffixes stripped.
Sparse: only addresses covered by a C array are present; unlisted addresses
are X/0 per the responder's policy.

Stdout: segment table (base byte address, word count, byte range).
"""

import argparse
import re
import sys
from pathlib import Path

ADDR_STEP = 8  # bytes per $readmemh address unit (64-bit word)

DEFAULT_SRC = Path(__file__).resolve().parents[1] / (
    "firmware/mbfw_diag_memimage.c"
)
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "stim/l2_buf.mem"

ARRAY_RE = re.compile(r"MI_([0-9a-fA-F]{16})\s*\[[^\]]*\]\s*[^=]*=\s*\{")
VALUE_RE = re.compile(r"0x([0-9a-fA-F]{1,16})ULL")
# memimage_t MEM_IMAGE [] = { {id, 0xADDRULL, word_count, MI_name}, ... };
TABLE_RE = re.compile(
    r"\{\s*-?\d+\s*,\s*0x([0-9a-fA-F]+)ULL\s*,\s*(\d+)\s*,\s*MI_([0-9a-fA-F]{16})\s*\}"
)


def parse(path: Path):
    """Return list of (base_byte_addr, [words]) in file order.

    Word counts are taken from the trailing `memimage_t MEM_IMAGE[]` table
    (the authoritative segment description); arrays whose initializers are
    shorter than their declared size (C zero-fills static storage) are padded
    with zeros so the .mem covers the full declared segment.
    """
    text = path.read_text()
    raw = {}
    order = []
    for m in ARRAY_RE.finditer(text):
        base = int(m.group(1), 16)
        # collect 0x....ULL values from here to the closing '};'
        end = text.find("};", m.end())
        if end == -1:
            raise ValueError(f"no closing '}};' after array MI_{m.group(1)}")
        raw[base] = [int(v, 16) for v in VALUE_RE.findall(text[m.end():end])]
        order.append(base)

    counts = {int(a, 16): int(n) for a, n, _ in TABLE_RE.findall(text)}
    segs = []
    for base in order:
        words = raw[base]
        want = counts.get(base, len(words))
        if len(words) > want:
            raise ValueError(
                f"MI_{base:016x}: {len(words)} initializers > declared {want}")
        if len(words) < want:
            print(f"  note: MI_{base:016x} zero-padded "
                  f"{len(words)} -> {want} words (C static zero-fill)")
            words = words + [0] * (want - len(words))
        segs.append((base, words))
    return segs


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    segs = parse(args.src)
    if not segs:
        sys.exit(f"no MI_ arrays found in {args.src}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    lines = [
        "// $readmemh image generated by port/scripts/memimage2hex.py",
        f"// source: {args.src}",
        "// @addr units: 64-bit words (physical byte address / 8);",
        "//      responder lookup: mem[pa >> 3]. One 16-hex-digit word per line.",
        "//      Each segment begins with an @<word-index> record (addr = base_pa/8).",
    ]
    for base, words in segs:
        lines.append(f"@{base // ADDR_STEP:x}")
        lines.extend(f"{w:016x}" for w in words)
        total += len(words)
        print(f"  base 0x{base:016x}  words {len(words):6d}  "
              f"bytes [0x{base:016x} .. 0x{base + 8 * len(words) - 1:016x}]")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"{len(segs)} segments, {total} words total -> {args.out}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate a LibreLane configuration for the full T1 core.

The generated configuration is written under port/build; the source list
and defines are resolved now so LibreLane does not need a file-list parser.
"""

import argparse
import os

from flist_common import DEFAULT_DEFINES, DEFAULT_INCDIRS, read_flist_files


def q(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=None)
    ap.add_argument("--flist", default="design/sys/iop/sparc/xst/sparc.flist")
    ap.add_argument("--extra", action="append", default=[])
    ap.add_argument("--define", action="append", default=None)
    ap.add_argument("--incdir", action="append", default=None)
    ap.add_argument("--top", required=True)
    ap.add_argument("--clock-port", required=True)
    ap.add_argument("--clock-period", default="10")
    ap.add_argument("--pdk", default="sky130A")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    if args.root:
        root = os.path.abspath(args.root)
    else:
        root = os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__))))

    flist = args.flist
    if not os.path.isabs(flist):
        flist = os.path.join(root, flist)
    files = [os.path.join(root, f) for f in read_flist_files(flist)]
    for extra in args.extra:
        if not os.path.isabs(extra):
            extra = os.path.join(root, extra)
        files.append(os.path.abspath(extra))

    defines = list(DEFAULT_DEFINES)
    if args.define:
        for extra in args.define:
            if extra not in defines:
                defines.append(extra)
    incdirs = args.incdir if args.incdir is not None else list(DEFAULT_INCDIRS)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as out:
        out.write("# Generated by port/scripts/gen_librelane_config.py\n")
        out.write("DESIGN_NAME: %s\n" % args.top)
        out.write("PDK: %s\n" % args.pdk)
        out.write("VERILOG_FILES:\n")
        for f in files:
            out.write("  - %s\n" % q(f))
        out.write("VERILOG_DEFINES:\n")
        for d in defines:
            out.write("  - %s\n" % q(d))
        out.write("VERILOG_INCLUDE_DIRS:\n")
        for incdir in incdirs:
            if not os.path.isabs(incdir):
                incdir = os.path.join(root, incdir)
            out.write("  - %s\n" % q(incdir))
        out.write("CLOCK_PORT: %s\n" % args.clock_port)
        out.write("CLOCK_PERIOD: %s\n" % args.clock_period)
        out.write("FP_CORE_UTIL: 40\n")
        out.write("PL_TARGET_DENSITY_PCT: 50\n")

    print("wrote %s (%d sources)" % (args.output, len(files)))


if __name__ == "__main__":
    main()
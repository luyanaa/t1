#!/usr/bin/env python3
"""Generate a Yosys synthesis script for the OpenSPARC T1 core.

The source list is Sun's synthesis file list (sparc.flist), not the
simulation file list: it contains the core SRAM models and excludes the
L2 and pad models that modern Yosys cannot parse or that are outside the
FPGA wrapper.

Example:
    python3 port/scripts/gen_fpga_ys.py \
        --extra design/sys/iop/rtl/iop_fpga.v \
        --extra port/fpga/t1_fpga_top.v \
        --top t1_fpga_top \
        --synth gowin --json port/build/t1_gowin.json \
        -o port/build/t1_fpga.ys
"""

import argparse
import os
import shlex

from flist_common import (
    DEFAULT_DEFINES, DEFAULT_INCDIRS, check_sources, read_flist_files)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=None,
                    help="repository root (default: inferred)")
    ap.add_argument("--flist", default="design/sys/iop/sparc/xst/sparc.flist")
    ap.add_argument("--extra", action="append", default=[],
                    help="additional Verilog source (repeatable)")
    ap.add_argument("--define", action="append", default=None,
                    help="preprocessor define (repeatable)")
    ap.add_argument("--incdir", action="append", default=None,
                    help="include directory (repeatable)")
    ap.add_argument("--top", required=True)
    ap.add_argument("--synth", choices=("gowin", "ecp5", "none"),
                    default="gowin")
    ap.add_argument("--family", default="gw5a",
                    help="Gowin family for synth_gowin (default: gw5a)")
    ap.add_argument("--json", default=None)
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    if args.root:
        root = os.path.abspath(args.root)
    else:
        root = os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__))))

    flist = args.flist
    if not os.path.isabs(flist):
        flist = os.path.join(root, flist)
    files = read_flist_files(flist, root=root)
    for extra in args.extra:
        if not os.path.isabs(extra):
            extra = os.path.join(root, extra)
        files.append(os.path.abspath(extra))
    check_sources(files, "FPGA synthesis")

    defines = list(DEFAULT_DEFINES)
    if args.define:
        for extra in args.define:
            if extra not in defines:
                defines.append(extra)
    incdirs = args.incdir if args.incdir is not None else list(DEFAULT_INCDIRS)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as out:
        out.write("# Generated by port/scripts/gen_fpga_ys.py\n")
        for name in defines:
            out.write("verilog_defaults -add %s\n" % shlex.quote("-D" + name))
        for incdir in incdirs:
            if not os.path.isabs(incdir):
                incdir = os.path.join(root, incdir)
            out.write("verilog_defaults -add %s\n" % shlex.quote("-I" + incdir))
        out.write("verilog_defaults -add -DNO_VERA\n")
        for start in range(0, len(files), 40):
            chunk = [os.path.abspath(f) for f in files[start:start + 40]]
            out.write("read_verilog %s\n" % " ".join(
                shlex.quote(f) for f in chunk))
        out.write("hierarchy -check -top %s\n" % shlex.quote(args.top))
        if args.synth == "gowin":
            out.write("synth_gowin -family %s -top %s" % (
                shlex.quote(args.family), shlex.quote(args.top)))
            if args.json:
                out.write(" -json %s" % shlex.quote(os.path.abspath(args.json)))
            out.write("\n")
        elif args.synth == "ecp5":
            out.write("synth_ecp5 -top %s" % shlex.quote(args.top))
            if args.json:
                out.write(" -json %s" % shlex.quote(os.path.abspath(args.json)))
            out.write("\n")
        out.write("stat\n")

    print("wrote %s (%d sources)" % (args.output, len(files)))


if __name__ == "__main__":
    main()
#!/usr/bin/env python3
"""Convert a linked SPARC ELF diag image into a sparse $readmemh file.

Output format matches the existing port convention (port/stim/l2_buf.mem,
see memimage2hex.py): sparse, one 16-hex-digit 64-bit big-endian word per
line, `@<idx>` records where idx = physical_byte_address / 8.  A Verilog
responder with `reg [63:0] mem[]` looks up data for physical address `pa`
as mem[pa >> 3] and gets the exact ELF bytes [pa, pa+7], big-endian
(SPARC is BE, so the low instruction is in the high half of the word,
matching tb_core_smoke.v where IFILL data[127:96] is the lowest address).

Usage: diag2hex.py <in.elf> <out.mem>
"""
import re
import subprocess
import sys


# VA->PA rule (see t1boot_min.s header / tb_core_smoke.v):
#   RED region VA 0xfffff0000000 -> PA 0xfff0000000  (PA = VA - 0xff0000000000)
#   low region  VA == PA (MMU off)
def readelf_sections(elf: str):
    out = subprocess.run(
        ["sparc64-linux-gnu-readelf", "-SW", elf],
        check=True, capture_output=True, text=True).stdout
    secs = []
    # .vectors  PROGBITS  fffff0000000  1000  001000  00 ...
    for m in re.finditer(
            r"^\s*\[\s*\d+\]\s+(\S+)\s+(\S+)\s+([0-9a-f]{8,16})\s+"
            r"([0-9a-f]+)\s+([0-9a-f]+)\s+(\S+)", out, re.M):
        name, _, addr, off, size, _flags = m.groups()
        if name in (".vectors", ".boot", ".text", ".data", ".bss", ".tstatus"):
            secs.append((name, int(addr, 16), int(off, 16), int(size, 16)))
    return secs


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    elf, out = sys.argv[1], sys.argv[2]
    with open(elf, "rb") as f:
        blob = f.read()
    lines = [
        "// $readmemh diag image generated by port/scripts/diag2hex.py",
        "// source: " + elf,
        "// @addr units: 64-bit words (physical byte address / 8);",
        "//      responder lookup: mem[pa >> 3]. One 16-hex-digit BE word per line.",
    ]
    for name, addr, off, size in readelf_sections(elf):
        if name == ".bss" or size == 0:
            continue
        pa = addr - 0xff0000000000 if addr >= 0xff0000000000 else addr
        idx = pa // 8
        lines.append("@%x" % idx)
        data = blob[off:off + size]
        if len(data) < size:           # file offset hole (NOBITS etc.)
            data += b"\0" * (size - len(data))
        for i in range(0, size, 8):
            word = data[i:i + 8].ljust(8, b"\0")
            lines.append(word.hex())
        print("diag2hex: %-10s pa=0x%012x size=0x%x" % (name, addr, size))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("diag2hex: wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
